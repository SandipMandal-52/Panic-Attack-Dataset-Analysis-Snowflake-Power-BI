-- 1. DATASET OVERVIEW
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(DISTINCT ID) AS UNIQUE_IDS,
    COUNT(*) - COUNT(DISTINCT ID) AS DUPLICATE_ID_COUNT
FROM PANIC_ATTACK_DATA;

-- 2. DUPLICATE ID CHECK
SELECT ID, COUNT(*) AS ID_COUNT
FROM PANIC_ATTACK_DATA
GROUP BY ID
HAVING COUNT(*) > 1
ORDER BY ID_COUNT DESC;

-- 3. MISSING VALUE CHECK
-- Snowflake COUNT(column) excludes SQL NULL values.
SELECT
    COUNT(*) AS TOTAL_RECORDS,
    COUNT(*) - COUNT(MEDICAL_HISTORY) AS MEDICAL_HISTORY_NULLS
FROM PANIC_ATTACK_DATA;

-- Check blanks and whitespace separately.
SELECT
    COUNT_IF(MEDICAL_HISTORY IS NULL) AS NULL_VALUES,
    COUNT_IF(TRIM(MEDICAL_HISTORY) = '') AS BLANK_OR_WHITESPACE_VALUES
FROM PANIC_ATTACK_DATA;

-- 4. CATEGORY DISTRIBUTIONS
SELECT GENDER, COUNT(*) AS TOTAL_RECORDS
FROM PANIC_ATTACK_DATA
GROUP BY GENDER
ORDER BY TOTAL_RECORDS DESC;

SELECT "TRIGGER" AS TRIGGER_CATEGORY, COUNT(*) AS TOTAL_RECORDS
FROM PANIC_ATTACK_DATA
GROUP BY "TRIGGER"
ORDER BY TOTAL_RECORDS DESC;

SELECT
    COALESCE(NULLIF(TRIM(MEDICAL_HISTORY), ''), 'Not recorded') AS MEDICAL_HISTORY_CATEGORY,
    COUNT(*) AS TOTAL_RECORDS
FROM PANIC_ATTACK_DATA
GROUP BY 1
ORDER BY TOTAL_RECORDS DESC;

-- 5. NUMERIC SUMMARY STATISTICS
SELECT
    AVG(PANIC_ATTACK_FREQUENCY) AS AVG_ATTACK_FREQUENCY,
    MEDIAN(PANIC_ATTACK_FREQUENCY) AS MEDIAN_ATTACK_FREQUENCY,
    MIN(PANIC_ATTACK_FREQUENCY) AS MIN_ATTACK_FREQUENCY,
    MAX(PANIC_ATTACK_FREQUENCY) AS MAX_ATTACK_FREQUENCY,
    AVG(DURATION_MINUTES) AS AVG_DURATION,
    MEDIAN(DURATION_MINUTES) AS MEDIAN_DURATION,
    MIN(DURATION_MINUTES) AS MIN_DURATION,
    MAX(DURATION_MINUTES) AS MAX_DURATION,
    STDDEV_SAMP(DURATION_MINUTES) AS STDDEV_DURATION,
    AVG(PANIC_SCORE) AS AVG_PANIC_SCORE,
    MEDIAN(PANIC_SCORE) AS MEDIAN_PANIC_SCORE,
    MIN(PANIC_SCORE) AS MIN_PANIC_SCORE,
    MAX(PANIC_SCORE) AS MAX_PANIC_SCORE
FROM PANIC_ATTACK_DATA;

-- 6. DURATION GROUP DISTRIBUTION
WITH DURATION_GROUPS AS (
    SELECT
        CASE
            WHEN DURATION_MINUTES BETWEEN 5 AND 14 THEN 'Short'
            WHEN DURATION_MINUTES BETWEEN 15 AND 24 THEN 'Medium'
            WHEN DURATION_MINUTES BETWEEN 25 AND 34 THEN 'Long'
            WHEN DURATION_MINUTES BETWEEN 35 AND 44 THEN 'Very Long'
            ELSE 'Outside defined range'
        END AS DURATION_GROUP,
        CASE
            WHEN DURATION_MINUTES BETWEEN 5 AND 14 THEN 1
            WHEN DURATION_MINUTES BETWEEN 15 AND 24 THEN 2
            WHEN DURATION_MINUTES BETWEEN 25 AND 34 THEN 3
            WHEN DURATION_MINUTES BETWEEN 35 AND 44 THEN 4
            ELSE 5
        END AS SORT_ORDER
    FROM PANIC_ATTACK_DATA
)
SELECT
    DURATION_GROUP,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2) AS PERCENTAGE
FROM DURATION_GROUPS
GROUP BY DURATION_GROUP, SORT_ORDER
ORDER BY SORT_ORDER;

-- 7. AVERAGE DURATION BY TRIGGER
SELECT
    "TRIGGER" AS TRIGGER_CATEGORY,
    COUNT(*) AS TOTAL_RECORDS,
    AVG(DURATION_MINUTES) AS AVG_DURATION,
    MIN(DURATION_MINUTES) AS MIN_DURATION,
    MAX(DURATION_MINUTES) AS MAX_DURATION
FROM PANIC_ATTACK_DATA
GROUP BY "TRIGGER"
ORDER BY AVG_DURATION DESC;

-- 8. GENDER COMPARISON
SELECT
    GENDER,
    COUNT(*) AS TOTAL_RECORDS,
    AVG(DURATION_MINUTES) AS AVG_DURATION,
    AVG(PANIC_SCORE) AS AVG_PANIC_SCORE
FROM PANIC_ATTACK_DATA
GROUP BY GENDER
ORDER BY AVG_DURATION DESC;

-- 9. AGE GROUP COMPARISON
WITH AGE_GROUPS AS (
    SELECT
        CASE
            WHEN AGE BETWEEN 18 AND 25 THEN '18-25'
            WHEN AGE BETWEEN 26 AND 35 THEN '26-35'
            WHEN AGE BETWEEN 36 AND 45 THEN '36-45'
            WHEN AGE BETWEEN 46 AND 55 THEN '46-55'
            WHEN AGE BETWEEN 56 AND 64 THEN '56-64'
            ELSE 'Outside defined range'
        END AS AGE_GROUP,
        CASE
            WHEN AGE BETWEEN 18 AND 25 THEN 1
            WHEN AGE BETWEEN 26 AND 35 THEN 2
            WHEN AGE BETWEEN 36 AND 45 THEN 3
            WHEN AGE BETWEEN 46 AND 55 THEN 4
            WHEN AGE BETWEEN 56 AND 64 THEN 5
            ELSE 6
        END AS SORT_ORDER,
        DURATION_MINUTES,
        PANIC_SCORE
    FROM PANIC_ATTACK_DATA
)
SELECT
    AGE_GROUP,
    COUNT(*) AS TOTAL_RECORDS,
    AVG(DURATION_MINUTES) AS AVG_DURATION,
    AVG(PANIC_SCORE) AS AVG_PANIC_SCORE
FROM AGE_GROUPS
GROUP BY AGE_GROUP, SORT_ORDER
ORDER BY SORT_ORDER;

-- 10. SLEEP CATEGORY COMPARISON
WITH SLEEP_GROUPS AS (
    SELECT
        CASE
            WHEN SLEEP_HOURS < 5 THEN 'Below 5 Hours'
            WHEN SLEEP_HOURS < 7 THEN '5-7 Hours'
            ELSE '7+ Hours'
        END AS SLEEP_CATEGORY,
        CASE
            WHEN SLEEP_HOURS < 5 THEN 1
            WHEN SLEEP_HOURS < 7 THEN 2
            ELSE 3
        END AS SORT_ORDER,
        DURATION_MINUTES,
        PANIC_SCORE
    FROM PANIC_ATTACK_DATA
)
SELECT
    SLEEP_CATEGORY,
    COUNT(*) AS TOTAL_RECORDS,
    AVG(PANIC_SCORE) AS AVG_PANIC_SCORE,
    AVG(DURATION_MINUTES) AS AVG_DURATION
FROM SLEEP_GROUPS
GROUP BY SLEEP_CATEGORY, SORT_ORDER
ORDER BY SORT_ORDER;

-- 11. MEDICAL HISTORY DISTRIBUTION
SELECT
    COALESCE(NULLIF(TRIM(MEDICAL_HISTORY), ''), 'Not recorded') AS MEDICAL_HISTORY_CATEGORY,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(COUNT(*) * 100.0 / (SELECT COUNT(*) FROM PANIC_ATTACK_DATA), 2) AS PERCENTAGE
FROM PANIC_ATTACK_DATA
GROUP BY 1
ORDER BY TOTAL_RECORDS DESC;

-- 12. MEDICATION AND THERAPY COMPARISON
-- Source CSV values are Yes/No. Confirm Snowflake values before relying on labels.
SELECT
    MEDICATION,
    THERAPY,
    COUNT(*) AS TOTAL_RECORDS,
    AVG(PANIC_SCORE) AS AVG_PANIC_SCORE,
    AVG(DURATION_MINUTES) AS AVG_DURATION
FROM PANIC_ATTACK_DATA
GROUP BY MEDICATION, THERAPY
ORDER BY TOTAL_RECORDS DESC;

